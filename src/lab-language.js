/** Return interface copy for the scenario's suggested grade, with accessible defaults. */
export function labLanguage(scenario) {
  const grade = String(scenario?.grade ?? '').replace(/[–—]/g, '-').replace(/\s+/g, '');
  const band = ['11-12', '11', '12'].includes(grade) ? '11-12'
    : ['9-10', '9', '10'].includes(grade) ? '9-10' : '7-8';
  return {...LANGUAGE[band]};
}
